/* Run against make serve. PLAYWRIGHT_MODULE/BROWSER_EXECUTABLE are optional. */
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const base = process.env.PS_TEST_URL || 'http://localhost:8090';
const snapshotQuery = process.env.PS_TEST_SNAPSHOT
  ? `snapshot=${encodeURIComponent(process.env.PS_TEST_SNAPSHOT)}`
  : 'snapshotlocked=true';
(async () => {
  const browser = await chromium.launch({headless: true, ...(process.env.BROWSER_EXECUTABLE ? {executablePath: process.env.BROWSER_EXECUTABLE} : {})});
  const page = await browser.newPage({viewport: {width: 1200, height: 1000}}), errors = [];
  page.on('pageerror', error => { errors.push(error.message); console.error('Page error:', error.message); });
  await page.goto(`${base}/?${snapshotQuery}`, {waitUntil: 'domcontentloaded'});
  await page.locator('#matchup-chart svg').waitFor();
  assert.equal(await page.locator('.matchup-card').count(), 2);
  assert.equal(await page.locator('.coverage-link').innerText(), 'Simulated fight · details ▾');
  assert.equal(await page.locator('#verification-progress, #source-evidence, #evidence').count(), 0);
  assert.equal(await page.locator('[name=mode]').inputValue(), 'duel');
  assert.equal(await page.locator('#fight-settings [name=armor]').count(), 0);
  const items = who => page.locator(`#${who}-card`).getAttribute('data-items').then(JSON.parse);
  const runID = () => page.locator('#results').getAttribute('data-run-id');
  const run = async () => { const before = await runID(); await page.locator('.matchup-run').click(); await page.waitForFunction(old => document.querySelector('#results').dataset.runId !== old, before); await page.waitForFunction(() => document.querySelector('#powerspike').dataset.stale === 'false'); };
  const addItem = async (who, id) => {
    await page.locator(`#${who}-card .item-slot`).first().click();
    await page.locator(`#item-picker [data-item-id="${id}"]`).click();
    await page.waitForFunction(({who,id}) => JSON.parse(document.getElementById(who+'-card').dataset.items)[0] === id, {who,id});
  };
  const original = await runID();
  await addItem('player', '1052'); await addItem('opponent', '1036');
  assert.equal((await items('player'))[0], '1052'); assert.equal((await items('opponent'))[0], '1036');
  assert.equal(await runID(), original, 'Editing replaced the completed fight');
  assert(await page.locator('.matchup-stale').isVisible());
  await run();
  console.log('Both inventories and explicit run passed.');
  await page.locator('[data-tab=runes][data-who=opponent]').click();
  await page.locator('[name=enemyshard1]').selectOption('5005');
  await page.waitForFunction(() => document.querySelector('#opponent-card [name=enemyshard1]').value === '5005' && document.querySelector('#powerspike').dataset.stale === 'true');
  await page.locator('[name=opponentlevel]').selectOption('6');
  await page.waitForFunction(() => document.querySelector('#opponent-card [name=opponentlevel]').value === '6');
  await page.locator('[data-tab=sequence][data-who=opponent]').click();
  await page.locator('[name=opponentpriority]').fill('e,q,r,w'); await page.locator('[name=opponentpriority]').press('Tab');
  await page.waitForFunction(() => JSON.parse(document.getElementById('configuration-data').dataset.json).scenario.target.strategy.priority[0] === 'e');
  const draft = JSON.parse(await page.locator('#configuration-data').getAttribute('data-json')).scenario;
  const previous = JSON.parse(await page.locator('#scenario-data').getAttribute('data-json')).scenario;
  assert.equal(draft.target.level, 6); assert.equal(previous.target.level, 18);
  await run();
  const canonical = JSON.parse(await page.locator('#scenario-data').getAttribute('data-json')).scenario;
  assert.equal(canonical.target.level, 6); assert.equal(canonical.target.loadout.shards[0], 5005); assert.deepEqual(canonical.target.strategy.priority, ['e','q','r','w']);
  assert.equal(canonical.player.champion, 'Annie');
  console.log('Opponent runes, level and strategy passed.');
  await page.locator('[data-tab=items][data-who=opponent]').click();
  const primaryBefore = await items('player'), opponentBefore = await items('opponent'), fightBeforeSearch = await runID();
  await page.locator('[data-search-open=opponent]').click();
  assert((await page.locator('#optimizer-title').innerText()).includes('Garen'));
  await page.locator('[name=searchbudget]').fill('1000');
  await page.locator('.optimizer-advanced > summary').click();
  await page.locator('[name=searchslots]').fill('2');
  await page.locator('[name=searchpool]').fill('1036,1042');
  await page.locator('[name=lockslot1]').check();
  await page.locator('#search-start').click();
  await page.waitForFunction(() => ['done','failed','cancelled'].includes(document.querySelector('#search-panel')?.dataset.status), undefined, {timeout: 90000});
  assert.equal(await page.locator('#search-panel').getAttribute('data-status'), 'done', await page.locator('#search-panel').innerText());
  assert.equal(await page.locator('#search-panel').getAttribute('data-search-who'), 'opponent');
  assert(await page.locator('.search-comparison').first().isVisible());
  await page.locator('[data-apply-build=opponent]').first().click();
  await page.waitForFunction(() => !document.querySelector('#optimizer-dialog').open);
  assert.deepEqual(await items('player'), primaryBefore, 'Opponent search changed the player');
  assert((await items('opponent')).includes('1036'), 'Kept item lost');
  assert.equal(await runID(), fightBeforeSearch, 'Apply replaced the completed fight');
  await page.locator('[data-undo=opponent]').click();
  await page.waitForFunction(expected => JSON.stringify(JSON.parse(document.getElementById('opponent-card').dataset.items)) === expected, JSON.stringify(opponentBefore));
  assert.deepEqual(await items('player'), primaryBefore);
  console.log('Opponent optimization, locks, comparison, apply and Undo passed.');
  const eventOptions = await page.locator('.matchup-event-select option').count(); assert(eventOptions > 2);
  await page.locator('.matchup-event-select').selectOption('0'); assert(await page.locator('.matchup-event-detail').isVisible());
  assert((await page.locator('.matchup-event-detail').innerText()).includes('damage'));
  await page.locator('[data-matchup-metric=damage]').click(); assert((await page.locator('.matchup-health').innerText()).includes('damage'));
  await page.locator('[data-matchup-metric=health]').click(); assert((await page.locator('.matchup-health').innerText()).includes('HP ('));
  for (const width of [1024,736,390,320]) {
    await page.setViewportSize({width,height:1000}); await page.waitForTimeout(150);
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `Overflow at ${width}`);
    if (width <= 650) {
      assert.equal(await page.locator('[data-collapse=player]').getAttribute('aria-expanded'), 'false');
      await page.locator('[data-collapse=player]').click();
      await page.locator('[data-tab=runes][data-who=player]').click();
      assert(await page.locator('[name=runepage1]').isVisible());
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `Expanded overflow at ${width}`);
      await page.locator('[data-collapse=player]').click();
    }
  }
  assert.deepEqual(errors, []);
  const noJS = await browser.newContext({javaScriptEnabled: false}), native = await noJS.newPage();
  await native.goto(`${base}/?${snapshotQuery}`, {waitUntil: 'domcontentloaded'});
  await native.locator('[name=level]').selectOption('6');
  await native.locator('#player-card noscript summary').click();
  await native.locator('noscript select[name=nativeslot1]').selectOption('1052');
  await Promise.all([native.waitForURL(url => url.searchParams.get('level') === '6'), native.locator('.matchup-run').click()]);
  assert.equal(await native.locator('[name=level]').inputValue(), '6');
  assert((await native.locator('#player-card').getAttribute('data-items')).includes('1052'));
  console.log('Shared chart, events, mobile and native form fallback passed.');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
